#!/usr/bin/env node
/**
 * The fork's only checkout-level setup: declare the fork's own files to the
 * updater, and confirm the user layer resolves to the external data repo.
 *
 * User data lives in ../career-ops-data and is reached through upstream's Data
 * Root (`.career-ops-data` marker or CAREER_OPS_ROOT, see DATA_CONTRACT.md), not
 * through symlinks. That replaced a transactional symlink manager here: with no
 * overlays in the worktree, a plain `git switch` / `git merge` touches nothing
 * of the user's, so there is nothing to detach and restore around an update.
 *
 *   setup   write config/local-paths.txt from fork/owned-paths.txt
 *   doctor  setup, then check the Data Root is an external git repository
 */
import { execFileSync } from 'child_process';
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'fs';
import { dirname, join, relative, sep } from 'path';
import { fileURLToPath } from 'url';
import { isMainModule } from './lib/is-main-module.mjs';
import { getCareerOpsRoot } from './path-resolver.mjs';

export const ROOT = dirname(fileURLToPath(import.meta.url));
export const MANIFEST_FILE = join(ROOT, 'fork', 'owned-paths.txt');
const USAGE = 'Usage:\n  node fork-sync.mjs setup|doctor\n  node fork-sync.mjs --help';

const lines = text => text.split(/\r?\n/).map(x => x.trim()).filter(x => x && !x.startsWith('#'));
const inside = (parent, child) => {
  const r = relative(realpathSync(parent), realpathSync(child));
  return r === '' || (!r.startsWith(`..${sep}`) && r !== '..');
};

export function ownedPaths(root = ROOT) {
  return lines(readFileSync(join(root, 'fork', 'owned-paths.txt'), 'utf8'));
}

export function writeLocalPaths(root = ROOT) {
  const body = '# Generated by node fork-sync.mjs setup; edit fork/owned-paths.txt instead.\n' + ownedPaths(root).join('\n') + '\n';
  mkdirSync(join(root, 'config'), { recursive: true });
  writeFileSync(join(root, 'config', 'local-paths.txt'), body);
  return body;
}

// Top-level symlinks into the data root are left over from the old overlay
// layout. Harmless (they point where the Data Root does) but no longer needed.
export function legacySymlinks(root, data) {
  return readdirSync(root).filter(name => {
    const p = join(root, name);
    return lstatSync(p).isSymbolicLink() && existsSync(p) && inside(data, p);
  }).sort();
}

export function doctor(root = ROOT, data = getCareerOpsRoot()) {
  if (!existsSync(data)) throw new Error(`data repository not found: ${data}`);
  if (realpathSync(data) === realpathSync(root)) {
    throw new Error('Data Root is the checkout itself; point .career-ops-data (or CAREER_OPS_ROOT) at the data repository');
  }
  execFileSync('git', ['rev-parse', '--is-inside-work-tree'], { cwd: data, stdio: 'ignore' });
  writeLocalPaths(root);
  return { ok: true, dataRoot: data, localPaths: ownedPaths(root).length, legacySymlinks: legacySymlinks(root, data) };
}

if (isMainModule(import.meta.url)) {
  try {
    const argv = process.argv.slice(2);
    if (argv.includes('--help') || argv.includes('-h')) { console.log(USAGE); process.exit(0); }
    const [command = 'doctor'] = argv;
    const result = command === 'doctor' ? doctor()
      : command === 'setup' ? { ok: true, localPaths: writeLocalPaths(ROOT).split('\n').filter(Boolean).length - 1 }
      : (() => { throw new Error(USAGE); })();
    console.log(JSON.stringify(result, null, 2));
  } catch (error) {
    console.error(`fork-sync: ${error.message}`);
    process.exitCode = 1;
  }
}
